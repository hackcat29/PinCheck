#!/usr/bin/env node
// Rebuilds web/vendor from pinned npm packages. The site serves these files itself (CSP 'self'),
// so PinCheck keeps zero runtime dependencies. Requires network access and npm.
//   node scripts/vendor.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, copyFileSync, readFileSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const PACKAGES = { three: '0.187.0', typegpu: '0.12.10', geist: '1.9.2', esbuild: '0.28.2' };
const out = new URL('../web/vendor/', import.meta.url).pathname;
const work = mkdtempSync(join(tmpdir(), 'pincheck-vendor-'));
mkdirSync(out, { recursive: true });

execFileSync('npm', ['init', '-y'], { cwd: work, stdio: 'ignore' });
execFileSync('npm', ['install', '--no-audit', '--no-fund', '--legacy-peer-deps', ...Object.entries(PACKAGES).map(([n, v]) => n + '@' + v)], { cwd: work, stdio: 'inherit' });
const { build } = await import(join(work, 'node_modules/esbuild/lib/main.js'));

const entries = {
  // three.js WebGPU renderer (falls back to WebGL 2 where WebGPU is unavailable), TSL and the bloom pass.
  'three.mjs': "export * from 'three/webgpu'; export * as TSL from 'three/tsl'; export { bloom } from 'three/examples/jsm/tsl/display/BloomNode.js';",
  // TypeGPU: typed WebGPU resources and pipelines.
  'typegpu.mjs': "export { default as tgpu } from 'typegpu'; export * as d from 'typegpu/data';",
};
for (const [file, source] of Object.entries(entries)) {
  writeFileSync(join(work, 'entry-' + file), source);
  await build({
    entryPoints: [join(work, 'entry-' + file)], outfile: join(out, file), bundle: true, format: 'esm',
    minify: true, target: 'es2022', legalComments: 'none', logLevel: 'warning', absWorkingDir: work,
  });
}

const fonts = { 'geist-sans.woff2': 'geist/dist/fonts/geist-sans/Geist-Variable.woff2', 'geist-mono.woff2': 'geist/dist/fonts/geist-mono/GeistMono-Variable.woff2' };
for (const [file, from] of Object.entries(fonts)) copyFileSync(join(work, 'node_modules', from), join(out, file));

const licenses = ['three', 'typegpu', 'geist'].map(name => {
  const pkg = JSON.parse(readFileSync(join(work, 'node_modules', name, 'package.json'), 'utf8'));
  let text = '';
  for (const candidate of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'OFL.txt', 'dist/fonts/geist-sans/LICENSE.TXT']) {
    try { text = readFileSync(join(work, 'node_modules', name, candidate), 'utf8'); break; } catch {}
  }
  return '## ' + name + ' ' + pkg.version + ' (' + pkg.license + ')\n\n' + (text || 'See https://www.npmjs.com/package/' + name) + '\n';
});
writeFileSync(join(out, 'LICENSES.md'), '# Third-party licenses for web/vendor\n\nGenerated by scripts/vendor.mjs.\n\n' + licenses.join('\n'));

const manifest = Object.fromEntries(['three.mjs', 'typegpu.mjs', ...Object.keys(fonts)].map(file => [file,
  createHash('sha256').update(readFileSync(join(out, file))).digest('hex')]));
writeFileSync(join(out, 'manifest.json'), JSON.stringify({ packages: PACKAGES, sha256: manifest }, null, 2) + '\n');
rmSync(work, { recursive: true, force: true });
console.log('web/vendor rebuilt:', Object.keys(manifest).join(', '));
