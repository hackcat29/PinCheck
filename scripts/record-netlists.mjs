#!/usr/bin/env node
// Reads the netlists behind the recorded examples from X Layer at each example's pinned block hash,
// checks them against the fingerprints in the report, and writes examples/netlists.json for the site.
//   node scripts/record-netlists.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRpc } from '../src/xlayer.mjs';
import { keccak256 } from '../src/keccak.mjs';

const root = new URL('../', import.meta.url);
const rpc = createRpc(process.env.X_LAYER_RPC || undefined);
const word = value => BigInt(value).toString(16).padStart(64, '0');
const index = JSON.parse(await readFile(new URL('examples/index.json', root), 'utf8'));
const circuits = {};

for (const example of index.examples) {
  const report = JSON.parse(await readFile(new URL('examples/' + example.report, root), 'utf8'));
  const pin = { blockHash: report.block.hash, requireCanonical: true };
  for (const [key, dep] of Object.entries(report.dependencies)) {
    if (circuits[key]) continue;
    const [address, id] = key.split(':');
    const raw = (await rpc('eth_call', [{ to: address, data: '0x3fc4be56' + word(id) }, pin])).slice(2);
    const length = Number(BigInt('0x' + raw.slice(64, 128)));
    const hex = raw.slice(128, 128 + length * 2);
    const bytes = Buffer.from(hex, 'hex');
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    if (sha256 !== dep.sha256) throw new Error(key + ': netlist does not match the recorded fingerprint');
    circuits[key] = {
      nIn: dep.nIn, nOut: dep.nOut, nState: dep.nState, gateCount: dep.gateCount,
      netlist: '0x' + hex, sha256, keccak256: '0x' + keccak256(bytes), block: report.block.hash,
    };
    console.log(key, dep.nIn + ' in', dep.nOut + ' out', bytes.length + ' bytes', 'verified');
  }
}

await writeFile(new URL('examples/netlists.json', root), JSON.stringify({
  description: 'Netlists of the circuits in the recorded examples, read from X Layer at each report\'s block hash. Generated by scripts/record-netlists.mjs.',
  circuits,
}, null, 2) + '\n');
